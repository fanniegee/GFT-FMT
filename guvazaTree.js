// ------------------------------------------------------------
// LEGACY NAME ANNOTATION HANDLING
//
// Parent-identifying parentheses are NOT automatically surnames.
//
// Examples:
//
//   Zekia Guvaza (Dzikamai)
//   Mary Guvaza (Zekia)
//   Joseph Guvaza (Edward)
//
// Personal second names are also preserved in fullName:
//
//   Dzikamai (Leonard) Guvaza
//   Masara (Edward) Guvaza
//
// We therefore do NOT parse parentheses into currentSurname.
// ------------------------------------------------------------

function extractLegacyAnnotation(record) {
  const current = String(record.currentSurname || "").trim();

  if (!current) {
    return null;
  }

  // These are known legacy annotations rather than canonical surnames.
  if (
    /^\(.*\)$/.test(current) ||
    /\)$/.test(current) &&
    !/^[A-Za-zÀ-ÿ'\/-]+$/.test(current)
  ) {
    return current;
  }

  return null;
}


// ------------------------------------------------------------
// WIFE NORMALIZATION
//
// Canonical values are ONLY:
// WIFE 1 ... WIFE 8
//
// Wife numbers are structural and branch/family-specific.
// They are NOT globally mapped to a particular woman's name.
// ------------------------------------------------------------

function normalizeWifeNo(oldWifeNo) {
  if (!oldWifeNo) return null;

  const value = String(oldWifeNo).trim();

  const match = value.match(/WIFE\s*([1-8])/i);

  if (!match) {
    return null;
  }

  return `WIFE ${match[1]}`;
}


