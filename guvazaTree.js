// ------------------------------------------------------------
// ZEKIA / HESKIA EXCEPTION
//
// ONLY GFT-GEN3-010 receives this silent exception.
// GFT-GEN4-054 remains a different individual.
// ------------------------------------------------------------

function canSilentlyResolveSpelling({
  systemId,
  submittedName,
  knownName
}) {

  if (
    systemId !== "GFT-GEN3-010"
  ) {
    return false;
  }

  if (!submittedName || !knownName) {
    return false;
  }

  const submitted =
    normalizeName(submittedName);

  const known =
    normalizeName(knownName);

  return (
    (
      submitted === "ZEKIA GUVAZA" &&
      known === "HESKIA GUVAZA"
    ) ||
    (
      submitted === "HESKIA GUVAZA" &&
      known === "ZEKIA GUVAZA"
    )
  );
}


function requiresFounderSpellingVerification({
  systemId,
  submittedName,
  knownName
}) {

  return !canSilentlyResolveSpelling({
    systemId,
    submittedName,
    knownName
  });
}


// ------------------------------------------------------------
// NEW GFT ID GENERATION
//
// Existing IDs are permanent.
// Never use record count as the next ID.
// ------------------------------------------------------------

function getHighestIdNumber(generation) {

  let highest = 0;

  guvazaTree.forEach(person => {

    if (
      Number(person.generation) !==
      Number(generation)
    ) {
      return;
    }

    const number =
      numericGftSuffix(person.systemId);

    if (number > highest) {
      highest = number;
    }
  });

  return highest;
}


function generatePermanentGftId(generation) {

  const highest =
    getHighestIdNumber(generation);

  return (
    `GFT-GEN${generation}-` +
    String(highest + 1).padStart(3, "0")
  );
}


// ------------------------------------------------------------
// REGISTER NEW MEMBER
// ------------------------------------------------------------

function registerNewMember({
  fullName,
  parentId,
  dateOfBirth = "",
  gender = null,
  currentSurname = null,
  email = "",
  wifeNo = null
}) {

  if (!fullName) {
    throw new Error(
      "Full name is required."
    );
  }

  if (!parentId) {
    throw new Error(
      "Parent ID is required."
    );
  }

  const parent =
    guvazaTreeById[parentId];

  if (!parent) {
    throw new Error(
      "Parent ID not verified."
    );
  }

  if (
    gender !== null &&
    gender !== "MALE" &&
    gender !== "FEMALE"
  ) {
    throw new Error(
      "Gender must be MALE or FEMALE."
    );
  }

  if (
    wifeNo !== null &&
    !isValidWifeChoice(wifeNo)
  ) {
    throw new Error(
      "Invalid wife selection."
    );
  }

  // Never reuse an existing GFT ID merely because
  // the applicant has the same name.
  const existingSamePerson =
    findSamePerson({
      fullName,
      parentId,
      dateOfBirth
    });

  if (existingSamePerson) {
    return existingSamePerson;
  }

  const generation =
    parent.generation + 1;

  const branch =
    parent.branch;

  const newSystemId =
    generatePermanentGftId(
      generation
    );

  const grandparent =
    parent.parentId
      ? guvazaTreeById[parent.parentId]
      : null;

  const femaleGrace =
    evaluateFemaleGrace({
      systemId: newSystemId,
      parentId,
      gender,
      rootSurname: "Guvaza"
    });

  if (!femaleGrace.allowed) {
    throw new Error(
      femaleGrace.reason
    );
  }

  const newMember = {

    fullName,

    rootSurname: "Guvaza",

    currentSurname:
      currentSurname || null,

    systemId: newSystemId,

    generation,

    branch,

    parentId,

    parentName:
      parent.fullName,

    grandparentId:
      grandparent
        ? grandparent.systemId
        : null,

    grandparentName:
      grandparent
        ? grandparent.fullName
        : null,

    dateOfBirth:
      dateOfBirth || null,

    gender,

    wifeNo:
      wifeNo || null,

    wifeName:
      wifeNo &&
      KNOWN_WIFE_NAMES[wifeNo]
        ? KNOWN_WIFE_NAMES[wifeNo]
        : null,

    email:
      email || null,

    emailVerified: false,

    isPlaceholder: false,

    isEditable: true,

    lineageStatus:
      "PENDING_VERIFICATION",

    identityStatus:
      "NOT_REVIEWED",

    founderVerificationStatus:
      "NOT_REVIEWED",

    beneficiaryStatus:
      "PENDING_VERIFICATION",

    walletEligible: false,

    payoutEligible: false
  };

  guvazaTree.push(newMember);

  guvazaTreeById[
    newSystemId
  ] = newMember;

  return newMember;
}


// ------------------------------------------------------------
// LINEAGE VERIFICATION
//
// Applicant must provide parent and grandparent.
// Grandparent is derived from verified parent.
// The applicant's claimed grandparent must match it.
// ------------------------------------------------------------

function verifyLineage({
  parentId,
  claimedParentName,
  claimedGrandparentName
}) {

  const parent =
    guvazaTreeById[parentId];

  if (!parent) {

    return {
      status:
        "LINEAGE_REVIEW_REQUIRED",

      verified: false,

      reason:
        "Parent record could not be verified."
    };
  }

  const actualParentName =
    normalizeName(
      parent.fullName
    );

  const actualGrandparent =
    parent.parentId
      ? guvazaTreeById[parent.parentId]
      : null;

  if (!actualGrandparent) {

    return {
      status:
        "LINEAGE_REVIEW_REQUIRED",

      verified: false,

      reason:
        "Grandparent could not be derived from the verified parent."
    };
  }

  const actualGrandparentName =
    normalizeName(
      actualGrandparent.fullName
    );

  const parentMatches =
    normalizeName(
      claimedParentName
    ) === actualParentName;

  const grandparentMatches =
    normalizeName(
      claimedGrandparentName
    ) === actualGrandparentName;

  if (
    !parentMatches ||
    !grandparentMatches
  ) {

    return {

      status:
        "LINEAGE_REVIEW_REQUIRED",

      verified: false,

      // Do NOT reveal the correct answer.
      reason:
        "The submitted lineage information does not match the verified family-tree relationship."
    };
  }

  return {

    status:
      "LINEAGE_CONFIRMED",

    verified: true,

    parentId:
      parent.systemId,

    grandparentId:
      actualGrandparent.systemId
  };
}


// ------------------------------------------------------------
// CANONICAL RECORD VALIDATION
// ------------------------------------------------------------

function validateCanonicalRecord(person) {

  const errors = [];

  if (!person.systemId) {
    errors.push(
      "Missing systemId"
    );
  }

  if (!person.fullName) {
    errors.push(
      "Missing fullName"
    );
  }

  if (
    !Object.prototype.hasOwnProperty.call(
      person,
      "rootSurname"
    )
  ) {
    errors.push(
      "Missing rootSurname"
    );
  }

  if (
    Object.prototype.hasOwnProperty.call(
      person,
      "secondSurname"
    )
  ) {
    errors.push(
      "secondSurname is forbidden"
    );
  }

  if (
    person.wifeNo !== null &&
    !isValidWifeChoice(person.wifeNo)
  ) {
    errors.push(
      "Invalid wifeNo"
    );
  }

  return {
    valid: errors.length === 0,
    errors
  };
}


// ------------------------------------------------------------
// COMPLETE TREE VALIDATION
// ------------------------------------------------------------

function validateGuvazaTree() {

  const idCheck =
    validatePermanentIds();

  const parentCheck =
    validateParentRelationships();

  const recordErrors = [];

  guvazaTree.forEach(person => {

    const result =
      validateCanonicalRecord(
        person
      );

    if (!result.valid) {
      recordErrors.push(
        `${person.systemId}: ` +
        result.errors.join(", ")
      );
    }
  });

  return {

    valid:
      idCheck.valid &&
      parentCheck.valid &&
      recordErrors.length === 0,

    recordCount:
      guvazaTree.length,

    errors: [
      ...idCheck.errors,
      ...parentCheck.errors,
      ...recordErrors
    ]
  };
}


