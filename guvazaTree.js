// BUILD CANONICAL TREE
// ------------------------------------------------------------

const guvazaTree = LEGACY_GUVAZA_TREE.map(
  createCanonicalRecord
);


// ------------------------------------------------------------
// INDEX BY PERMANENT GFT ID
// ------------------------------------------------------------

const guvazaTreeById = Object.create(null);

guvazaTree.forEach(person => {
  guvazaTreeById[person.systemId] = person;
});


// ------------------------------------------------------------
// RESOLVE PARENT / GRANDPARENT NAMES
// ------------------------------------------------------------

guvazaTree.forEach(person => {

  if (person.parentId) {

    const parent =
      guvazaTreeById[person.parentId];

    if (parent) {

      person.parentName =
        parent.fullName;

      if (parent.parentId) {

        person.grandparentId =
          parent.parentId;

        const grandparent =
          guvazaTreeById[parent.parentId];

        if (grandparent) {
          person.grandparentName =
            grandparent.fullName;
        }
      }
    }
  }
});


// ------------------------------------------------------------
// ID VALIDATION
// ------------------------------------------------------------

function validatePermanentIds() {

  const seen = new Set();
  const errors = [];

  guvazaTree.forEach(person => {

    if (!person.systemId) {
      errors.push(
        "Missing systemId for " + person.fullName
      );
      return;
    }

    if (seen.has(person.systemId)) {
      errors.push(
        "Duplicate systemId: " + person.systemId
      );
    }

    seen.add(person.systemId);
  });

  return {
    valid: errors.length === 0,
    errors
  };
}


// ------------------------------------------------------------
// PARENT VALIDATION
// ------------------------------------------------------------

function validateParentRelationships() {

  const errors = [];

  guvazaTree.forEach(person => {

    if (person.generation === 1) {
      return;
    }

    if (!person.parentId) {
      errors.push(
        `${person.systemId}: missing parentId`
      );
      return;
    }

    const parent =
      guvazaTreeById[person.parentId];

    if (!parent) {
      errors.push(
        `${person.systemId}: parent ${person.parentId} does not exist`
      );
      return;
    }

    if (
      person.generation !==
      parent.generation + 1
    ) {
      errors.push(
        `${person.systemId}: generation does not follow parent generation`
      );
    }
  });

  return {
    valid: errors.length === 0,
    errors
  };
}


// ------------------------------------------------------------
// DUPLICATE NAME CHECK
//
// Same name DOES NOT mean same person.
// ------------------------------------------------------------

function findPeopleByName(fullName) {

  const wanted = normalizeName(fullName);

  return guvazaTree.filter(person =>
    normalizeName(person.fullName) === wanted
  );
}


function findPeopleByParent(fullName, parentId) {

  const wanted = normalizeName(fullName);

  return guvazaTree.filter(person =>
    normalizeName(person.fullName) === wanted &&
    person.parentId === parentId
  );
}


function findSamePerson({
  fullName,
  parentId,
  dateOfBirth = ""
}) {

  const wanted = normalizeName(fullName);

  return guvazaTree.find(person => {

    if (
      normalizeName(person.fullName) !== wanted
    ) {
      return false;
    }

    if (
      person.parentId !== parentId
    ) {
      return false;
    }

    if (!dateOfBirth) {
      return false;
    }

    return (
      person.dateOfBirth === dateOfBirth
    );
  }) || null;
}


// ------------------------------------------------------------
// FEMALE GRACE
//
// Female grace is based on actual biological lineage:
//
// Guvaza
//   -> Guvaza daughter
//      -> direct biological child
//
// It does NOT use generation number alone.
//
// A child beyond that direct-child level is blocked.
// ------------------------------------------------------------

function getAncestorChain(systemId) {

  const chain = [];
  const visited = new Set();

  let current =
    guvazaTreeById[systemId];

  while (current) {

    if (visited.has(current.systemId)) {
      break;
    }

    visited.add(current.systemId);

    chain.push(current);

    if (!current.parentId) {
      break;
    }

    current =
      guvazaTreeById[current.parentId];
  }

  return chain;
}


function isDirectChildOfGuvazaDaughter(person) {

  if (!person || !person.parentId) {
    return false;
  }

  const parent =
    guvazaTreeById[person.parentId];

  if (!parent) {
    return false;
  }

  if (parent.gender !== "FEMALE") {
    return false;
  }

  if (!parent.parentId) {
    return false;
  }

  const grandparent =
    guvazaTreeById[parent.parentId];

  if (!grandparent) {
    return false;
  }

  return (
    grandparent.systemId ===
    "GFT-GEN1-01"
  );
}


function hasMaleGuvazaGrandparent(person) {

  if (!person || !person.parentId) {
    return false;
  }

  const parent =
    guvazaTreeById[person.parentId];

  if (!parent || !parent.parentId) {
    return false;
  }

  const grandparent =
    guvazaTreeById[parent.parentId];

  if (!grandparent) {
    return false;
  }

  return (
    grandparent.rootSurname === "Guvaza" &&
    grandparent.gender === "MALE"
  );
}


function evaluateFemaleGrace(person) {

  if (!person) {
    return {
      allowed: false,
      level: 0,
      reason: "Person not found."
    };
  }

  // A biological child directly descended from a Guvaza
  // daughter is permitted.
  if (
    isDirectChildOfGuvazaDaughter(person)
  ) {
    return {
      allowed: true,
      level: 2,
      requiresFounderApproval: true,
      canReceivePayout: false,
      reason:
        "Direct biological child of a Guvaza daughter."
    };
  }

  // A person who is themselves a Guvaza daughter
  // may register normally.
  if (
    person.parentId === "GFT-GEN1-01" &&
    person.gender === "FEMALE"
  ) {
    return {
      allowed: true,
      level: 1,
      requiresFounderApproval: false,
      canReceivePayout: false,
      reason:
        "Direct Guvaza daughter."
    };
  }

  // If the person's relevant Guvaza ancestor is female
  // and the person is beyond the direct-child limit,
  // registration is blocked under female grace.
  const chain =
    getAncestorChain(person.systemId);

  const rootIndex =
    chain.findIndex(
      p => p.systemId === "GFT-GEN1-01"
    );

  if (rootIndex >= 0) {

    const pathToRoot =
      chain.slice(0, rootIndex);

    const femaleGuvazaAncestor =
      pathToRoot.find(
        p =>
          p.gender === "FEMALE" &&
          p.rootSurname === "Guvaza"
      );

    if (femaleGuvazaAncestor) {

      return {
        allowed: false,
        level: 3,
        requiresFounderApproval: false,
        canReceivePayout: false,
        reason:
          "Female grace ends with the direct biological children of Guvaza daughters."
      };
    }
  }

  return {
    allowed: true,
    level: 0,
    requiresFounderApproval: false,
    canReceivePayout: false,
    reason:
      "No female-grace restriction applies."
  };
}


// ------------------------------------------------------------
// CHILD REGISTRATION ELIGIBILITY
// ------------------------------------------------------------

function canRegisterChildren(person) {

  if (!person) {
    return false;
  }

  const result =
    evaluateFemaleGrace(person);

  return result.allowed;
}


// ------------------------------------------------------------
// PAYOUT
//
// Registration NEVER grants payout.
// Only Founder verification can grant payout.
// ------------------------------------------------------------

function canReceivePayout(person) {

  if (!person) {
    return false;
  }

  return (
    person.founderVerificationStatus ===
      "FOUNDER_VERIFIED" &&

    person.beneficiaryStatus ===
      "FOUNDER_VERIFIED" &&

    person.walletEligible === true &&

    person.payoutEligible === true
  );
}


function isPayoutEligible(person) {
  return canReceivePayout(person);
}


